function applyAttrI18n() {
    ATTR_I18N.forEach(([sel, attr, key]) => {
        const el = document.querySelector(sel);
        if (el) el.setAttribute(attr, t(key));
    });
}

// JS-owned elements whose *default* text should follow the locale, but whose
// content is later replaced by live app state (badges, status lines). Only
// retranslate when the current text still IS that default (in any locale).
const DYNAMIC_DEFAULTS = [
    ['pdf-state',    'Idle'],
    ['ocr-state',    'Idle'],
    ['wav-state',    'Idle'],
    ['img-count',    '0 files'],
    ['ocr-output',   'Paste an image, drop it, or upload to begin…'],
    ['sig-statline', 'No image loaded.'],
    ['ocr-loadtext', 'Preparing OCR engine…'],
];
function applyDynamicDefaults() {
    DYNAMIC_DEFAULTS.forEach(([id, key]) => {
        const el = document.getElementById(id);
        if (!el) return;
        const cur = el.textContent.trim();
        const isDefault = cur === key ||
            Object.keys(I18N).some((loc) => I18N[loc][key] === cur);
        if (isDefault) el.textContent = t(key);
    });
}

function currentFleetLang() { return (window.CarinoLang && window.CarinoLang.current) || 'en'; }

function applyI18n() {
    setLocale(currentFleetLang());
    applyStaticI18n();
    applyAttrI18n();
    applyDynamicDefaults();
}

// Bridge for the inline app scripts (they call T(), which resolves lazily).
window.CarinoI18N = { t, apply: applyI18n };

// carino-lang.js is deferred and executes before DOMContentLoaded (this script
// is also deferred and placed after it), so CarinoLang exists by then.
window.addEventListener('DOMContentLoaded', applyI18n);
window.addEventListener('carino:langchange', applyI18n);
