#!/usr/bin/env python3
"""Rewrite VERSION and the SHELL precache list in sw.js from what the repo holds.

Adapted from Carino Fiscal's tools/build_sw.py, the fleet's reference for this
pattern. Files differs in one way: most of its weight is vendor/ (pdf.js,
Tesseract and its models, libheif, the metadata parsers: tens of megabytes),
and nobody who only wants to strip a JPEG should download all of that on a
first visit. So the shell is precached and vendor/ is not: sw.js caches each
vendor file the first time the app actually asks for it.

VERSION is still the sha256 of every shipped file, vendor/ included, so a new
pdf.js or a new model invalidates the vendor runtime cache as well as the
shell. A build with identical bytes keeps its caches; one changed byte
anywhere gets new ones. sw.js's own bytes change with VERSION, which is what
makes every installed copy pick the new build up.

The list is derived, not written, so a new js/ws/*.js or css/*.css needs no
second edit. tests/sw.test.mjs runs the --check mode, and
Carino-Systems/propagate.sh rebuilds sw.js after it copies the shared
carino-* files in (a copied file changes the hash).

    python3 -I tools/build_sw.py            # rewrite the generated block
    python3 -I tools/build_sw.py --check    # non-zero if it has drifted
"""

import hashlib
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SW = ROOT / "sw.js"

BEGIN = "// --- begin generated by tools/build_sw.py ---"
END = "// --- end generated ---"

# What a browser can be asked to load. Licences, the README and the tooling are
# shipped by git, not by the app.
SERVED = {".html", ".js", ".mjs", ".css", ".json", ".webp", ".png", ".jpg", ".svg",
          ".woff2", ".wasm", ".gz"}

# Never served to the app: the tests, the tooling, CI, git.
SKIP_DIRS = {".git", ".github", "tests", "tools", "node_modules"}

# A worker that caches its own script is how a bad deploy becomes permanent.
SKIP_FILES = {"sw.js"}

FONT_URL = re.compile(r"url\(\s*[\"']?\./([^)\"'\s]+)[\"']?\s*\)")


def shipped_assets() -> list[str]:
    """Every servable file, vendor/ included: what VERSION hashes."""
    assets = []
    for path in sorted(ROOT.rglob("*")):
        if not path.is_file():
            continue
        rel = path.relative_to(ROOT).as_posix()
        if set(rel.split("/")[:-1]) & SKIP_DIRS or rel in SKIP_FILES:
            continue
        if path.suffix in SERVED:
            assets.append(rel)
    return assets


def shell_assets() -> list[str]:
    """What the app cannot start without, precached on install.

    Not here: vendor/** (cached on first use), og.jpg and screenshot.webp
    (for link previews, never loaded by the page), 404.html, sw.js.
    """
    shell = ["index.html", "i18n.js", "logo.svg", "logo-color.svg", "logo.webp"]
    shell += sorted(p.relative_to(ROOT).as_posix() for p in (ROOT / "css").glob("*.css"))
    shell += sorted(p.relative_to(ROOT).as_posix() for p in (ROOT / "js").rglob("*.js"))
    shell += sorted(p.name for p in ROOT.glob("carino-*.js"))
    shell += sorted(p.name for p in ROOT.glob("carino-*.css"))
    fonts_css = ROOT / "fonts" / "carino-fonts.css"
    if fonts_css.exists():
        shell.append("fonts/carino-fonts.css")
        refs = FONT_URL.findall(fonts_css.read_text(encoding="utf-8"))
        shell += sorted({"fonts/" + r for r in refs})
    # './' and 'index.html' are two cache keys for the same bytes; a navigation
    # to the bare origin only matches the first.
    return ["./"] + [r for r in dict.fromkeys(shell) if (ROOT / r).is_file()]


def render(name: str, urls: list[str]) -> str:
    body = "".join(f"  '{u}',\n" for u in urls)
    return f"const {name} = [\n{body}];\n"


def generate() -> tuple[str, list[str], str]:
    digest = hashlib.sha256()
    for rel in shipped_assets():
        digest.update(rel.encode("utf-8"))
        digest.update(b"\0")
        digest.update((ROOT / rel).read_bytes())
    version = digest.hexdigest()[:16]
    shell = shell_assets()
    block = (
        "// sha256 of every shipped file, vendor/ included (cache names carry it).\n"
        f"const VERSION = '{version}';\n\n"
        "// Precached on install. vendor/ is not listed: it is cached on first use.\n"
        f"{render('SHELL', shell)}"
    )
    return version, shell, block


def current_block(src: str):
    found = re.search(re.escape(BEGIN) + r"\n(.*?)" + re.escape(END), src, flags=re.S)
    return found.group(1) if found else None


def check(src: str, version: str, shell: list[str], block: str) -> int:
    have = current_block(src)
    if have is None:
        print("sw.js has no generated block: restore the markers and run tools/build_sw.py")
        return 1
    if have == block:
        return 0
    listed = set(re.findall(r"^  '(.+)',$", have, flags=re.M))
    for rel in sorted(set(shell) - listed):
        print(f"{rel} is part of the shell but sw.js does not precache it")
    for rel in sorted(listed - set(shell)):
        print(f"sw.js precaches {rel}, which is not in the shell any more (install would fail)")
    if f"const VERSION = '{version}';" not in have:
        print("sw.js VERSION is not the hash of what ships: installed copies would never update")
    print("run: python3 -I tools/build_sw.py")
    return 1


def main(argv: list[str]) -> int:
    if not SW.exists():
        print(f"missing {SW}")
        return 1
    version, shell, block = generate()
    src = SW.read_text(encoding="utf-8")
    if "--check" in argv:
        return check(src, version, shell, block)
    if BEGIN not in src or END not in src:
        print("sw.js has no generated block: restore the markers before running this")
        return 1
    out = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END),
                 lambda _: BEGIN + "\n" + block + END, src, flags=re.S)
    if out != src:
        SW.write_text(out, encoding="utf-8")
    print(f"sw.js: VERSION {version}, {len(shell)} shell entries"
          f"{'' if out != src else ' (unchanged)'}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
