// Carino Files: offline service worker.
//
// After one visit the app opens with no connection. The shell (index.html,
// css/, js/, i18n.js, the shared carino-* files, the fonts, the logos) is
// precached on install. vendor/ (pdf.js, Tesseract and its models, libheif,
// the metadata parsers: tens of megabytes) is cached the first time the app
// asks for each file, so a visit that only strips a JPEG downloads none of it.
//
// The shell can never be stale forever:
//   - HTML is network-first (about 3 s), falling back to the cached copy.
//   - VERSION is the sha256 of every shipped file (tools/build_sw.py), so a
//     deploy changes this file's bytes, the browser installs the new worker,
//     and activate drops every files-* cache of another VERSION.
//   - When the network serves an index.html that differs from the cached one
//     (a deploy this worker has not caught up with yet), the shell assets are
//     fetched network-first too, so a new page never runs old scripts.
//
// Same-origin GET only. Cross-origin requests and sw.js itself pass through.
// CarinoBridge (#carino-bridge) is postMessage, not fetch, and a fragment
// never reaches the network: that navigation is just './'.
//
// The block below is generated: run python3 -I tools/build_sw.py.

