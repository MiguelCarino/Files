const SHELL_CACHE = 'files-shell-' + VERSION;
const VENDOR_CACHE = 'files-vendor-' + VERSION;
const SCOPE = new URL('./', self.location.href);
const HTML_TIMEOUT = 3000;

const abs = (rel) => new URL(rel, SCOPE).href;
const SHELL_URLS = new Set(SHELL.map(abs));
// The shell has to come from the deploy, not from an HTTP cache that may still
// hold the previous build's bytes under the same URL.
const fromNetwork = (url) => new Request(url, { cache: 'reload' });
const isFont = (url) => /\.woff2$/.test(url);

// Set when the network's index.html differs from the cached one (see above).
let shellBehind = false;

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(SHELL_CACHE).then((cache) =>
    // All or nothing for what the app cannot start without; a font that fails
    // costs a fallback face, not the offline app.
    cache.addAll(SHELL.filter((u) => !isFont(u)).map((u) => fromNetwork(abs(u))))
      .then(() => Promise.allSettled(SHELL.filter(isFont).map((u) => cache.add(fromNetwork(abs(u))))))
  ).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(caches.keys()
    .then((keys) => Promise.all(keys
      .filter((k) => k.startsWith('files-') && k !== SHELL_CACHE && k !== VENDOR_CACHE)
      .map((k) => caches.delete(k))))
    .then(() => self.clients.claim()));
});

// Worth keeping: a whole, ordinary same-origin response.
const keepable = (res) => !!res && res.ok && res.status === 200 && res.type === 'basic';

function cachedShell(){
  return caches.open(SHELL_CACHE).then((c) => c.match(abs('index.html')));
}

// Network-first with a timeout. A slow network still wins over nothing: when
// there is no cached copy the fetch is simply awaited.
function html(request){
  const net = fetch(request).then((res) => {
    if(!keepable(res)) return res;
    // Compare with the cached shell; a difference means a deploy is ahead of
    // this worker (see the header).
    return Promise.all([res.clone().text(), cachedShell().then((c) => (c ? c.text() : null))])
      .then(([fresh, old]) => { if(old != null && fresh !== old) shellBehind = true; return res; }, () => res);
  });
  const fallback = () => cachedShell().then((c) => c || Response.error());
  let timer;
  const late = new Promise((resolve) => {
    timer = setTimeout(() => cachedShell().then((c) => { if(c) resolve(c); }), HTML_TIMEOUT);
  });
  return Promise.race([net.catch(() => fallback()), late]).finally(() => clearTimeout(timer));
}

// vendor/**: cache-first, filled on first use. A Range request (partial
// content) passes straight through and is never stored.
function vendor(request){
  if(request.headers.has('range')) return fetch(request);
  return caches.open(VENDOR_CACHE).then((cache) => cache.match(request, { ignoreSearch: true }).then((hit) => {
    if(hit) return hit;
    return fetch(request).then((res) => {
      if(keepable(res)) cache.put(request, res.clone()).catch(() => {});
      return res;
    });
  }));
}

// Shell assets: cache-first, the network filling any gap. Network-first while
// a deploy is ahead of this worker.
function shellAsset(request, url){
  return caches.open(SHELL_CACHE).then((cache) => {
    // While behind, past the HTTP cache too: it may still hold the previous
    // build's bytes under the same URL (GitHub Pages sends max-age=600).
    const fromNet = () => fetch(shellBehind ? fromNetwork(url) : request).then((res) => {
      if(keepable(res) && !shellBehind) cache.put(url, res.clone()).catch(() => {});
      return res;
    });
    if(shellBehind) return fromNet().catch(() => cache.match(url).then((hit) => hit || Response.error()));
    return cache.match(url).then((hit) => hit || fromNet());
  });
}

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if(request.method !== 'GET') return;
  const url = new URL(request.url);
  if(url.origin !== SCOPE.origin || !url.pathname.startsWith(SCOPE.pathname)) return;
  const rel = url.pathname.slice(SCOPE.pathname.length);
  if(rel === 'sw.js') return;

  const accept = request.headers.get('accept') || '';
  const isPage = request.mode === 'navigate' || request.destination === 'document'
    || ((rel === '' || rel === 'index.html') && accept.includes('text/html'));
  if(isPage){
    event.respondWith(html(request));
    return;
  }
  if(rel.startsWith('vendor/')){
    event.respondWith(vendor(request));
    return;
  }
  const key = url.origin + url.pathname;
  if(SHELL_URLS.has(key)){
    event.respondWith(shellAsset(request, key));
  }
  // Anything else (og.jpg, 404.html, …) goes to the network untouched.
});
