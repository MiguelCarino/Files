// The offline service worker: sw.js's generated block (tools/build_sw.py) is
// current, every precached path exists, vendor/ is runtime-cached only, and
// the worker parses.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { existsSync } from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { ROOT, read } from './load.mjs';

const BEGIN = '// --- begin generated by tools/build_sw.py ---';
const END = '// --- end generated ---';

function block() {
  const src = read('sw.js');
  const a = src.indexOf(BEGIN), b = src.indexOf(END);
  assert.ok(a >= 0 && b > a, 'sw.js has its generated block');
  const ctx = vm.createContext({});
  vm.runInContext(src.slice(a + BEGIN.length, b) + '\n;this.__V = VERSION; this.__S = SHELL;', ctx);
  return { VERSION: ctx.__V, SHELL: Array.from(ctx.__S) };
}

test('tools/build_sw.py --check: the generated block is current', () => {
  const r = spawnSync('python3', ['-I', 'tools/build_sw.py', '--check'], { cwd: ROOT, encoding: 'utf8' });
  if (r.error && r.error.code === 'ENOENT') return;   // no python3 here: nothing to run it with
  assert.equal(r.status, 0, (r.stdout || '') + (r.stderr || ''));
});

test('SHELL: every path exists; no vendor/, no sw.js; the app shell is in it', () => {
  const { VERSION, SHELL } = block();
  assert.match(VERSION, /^[0-9a-f]{16}$/);
  assert.equal(SHELL[0], './');
  for (const p of SHELL.slice(1)) assert.ok(existsSync(path.join(ROOT, p)), 'missing ' + p);
  assert.deepEqual(SHELL.filter((p) => p.startsWith('vendor/')), []);
  assert.ok(!SHELL.includes('sw.js'));
  assert.equal(new Set(SHELL).size, SHELL.length, 'no duplicates');
  for (const p of ['index.html', 'i18n.js', 'js/core.js', 'js/expose.js', 'js/hash-worker.js',
    'carino-navbar.js', 'carino-ui.css', 'fonts/carino-fonts.css', 'logo.svg', 'logo.webp'])
    assert.ok(SHELL.includes(p), p + ' precached');
  for (const p of ['og.jpg', 'screenshot.webp', '404.html']) assert.ok(!SHELL.includes(p), p + ' not precached');
  assert.ok(!SHELL.some((p) => /^(tests|tools)\//.test(p)));
});

test('every stylesheet and classic script index.html loads is in SHELL', () => {
  const { SHELL } = block();
  const html = read('index.html');
  const refs = [...html.matchAll(/<(?:script|link)\b[^>]*\s(?:src|href)="([^"]+)"/g)]
    .map((m) => m[1]).filter((u) => !/^[a-z]+:|^\/\//i.test(u));
  for (const u of refs) assert.ok(SHELL.includes(u), u + ' is loaded by index.html but not precached');
});

test('node --check sw.js', () => {
  const r = spawnSync(process.execPath, ['--check', 'sw.js'], { cwd: ROOT, encoding: 'utf8' });
  assert.equal(r.status, 0, r.stderr);
});

test('sw.js is registered from a classic script, never as a <script>', () => {
  const html = read('index.html');
  assert.doesNotMatch(html, /<script\b[^>]*\bsrc="sw\.js"/);
  assert.match(read('js/expose.js'), /serviceWorker\.register\('sw\.js'\)/);
});
